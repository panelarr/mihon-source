// Generates TypeScript types for the API from the OpenAPI document, which is itself
// generated from the protos (`make gen`). Run it after the API changes:
//
//   npm run gen:api          writes src/api/schema.d.ts
//   npm run gen:api:check    fails when src/api/schema.d.ts is out of date (run by `make check`)
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const source = new URL("../../service/src/main/resources/openapi/openapi.yaml", import.meta.url);
const target = new URL("../src/api/schema.d.ts", import.meta.url);

const header = `// Generated by scripts/gen-api.mjs from service/src/main/resources/openapi/openapi.yaml.
// Don't edit by hand: run \`npm run gen:api\` (or \`./gradlew :admin:genApi\`).

`;

const ast = await openapiTS(source, { alphabetize: false, defaultNonNullable: false });
const generated = header + astToString(ast);

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== generated) {
    console.error("src/api/schema.d.ts is out of date with the OpenAPI document. Run `npm run gen:api`.");
    process.exit(1);
  }
  console.log("src/api/schema.d.ts is up to date.");
} else {
  await writeFile(target, generated);
  console.log("Wrote src/api/schema.d.ts");
}
